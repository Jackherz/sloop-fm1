# SLOOP JR: measure what the firmware costs and what each feature-cut is worth.
#
#   tools/measure_flash.sh            (needs the JieLi toolchain + AC79 SDK, as ./build.sh)
#   tools/measure_flash.sh --quick    (baseline + the two cheapest cuts only)
#
# Why: the app slot is 581,564 B and the 2.8.5 build only links by falling back to a text boot logo,
# so anything new (a kid mode, a tutorial layer) has to be paid for. This script prints, for each
# build variant, the image size and its delta against the baseline, plus the RAM and pool figures the
# linker check reports. Run it before designing anything that adds code.
#
# It writes build/measurements.md (a table you can paste into a plan or a commit message).
# Nothing in the tree is modified: every variant is an environment flag the build already honours.
set -e
cd "$(dirname "$0")/.."

JIELI_TOOLCHAIN="${JIELI_TOOLCHAIN:-$HOME/.jieli/toolchain}"
AC79_SDK="${AC79_SDK:-$HOME/fw-AC79_AIoT_SDK}"
export JIELI_TOOLCHAIN AC79_SDK
PY="${PYTHON:-python3}"
OUT=build/measure
LOG=$OUT/log
mkdir -p "$OUT" "$LOG"

[ -x "$JIELI_TOOLCHAIN/pi32v2/bin/clang" ] || { echo "measure_flash: no toolchain in $JIELI_TOOLCHAIN (tools/get_toolchain.sh)"; exit 1; }
[ -f "$AC79_SDK/cpu/wl82/tools/uboot.boot" ] || { echo "measure_flash: no AC79 SDK in $AC79_SDK"; exit 1; }
"$PY" -c 'import PIL' 2>/dev/null || { echo "measure_flash: $PY has no Pillow (pip3 install Pillow)"; exit 1; }

QUICK=0
[ "$1" = "--quick" ] && QUICK=1

# --- the data blobs first: these need no cross-compiler, and they are half the image -------------
SAMPLES=$(grep -o 'SMP_DATA\[[0-9]*\]' build/gen/felucca_samples.h 2>/dev/null | head -1 | tr -dc '0-9')
[ -n "$SAMPLES" ] || { "$PY" tools/gen_samples.py build/gen/felucca_samples.h >/dev/null 2>&1 || true; SAMPLES=$(grep -o 'SMP_DATA\[[0-9]*\]' build/gen/felucca_samples.h | head -1 | tr -dc '0-9'); }
ICONS=$(grep -o 'FELUCCA_ICON_[A-Z_]*\[[0-9]*\]' build/gen/felucca_icons.h 2>/dev/null | head -1 | tr -dc '0-9')
LOGO=$(grep -o 'SLOOP_LOGO_RLE\[[0-9]*\]\|SLOOP_SPLASH_[A-Z]*\[[0-9]*\]' build/gen/sloop_logo.h 2>/dev/null | head -1 | tr -dc '0-9')

# --- one build ---------------------------------------------------------------------------------
# $1 = label, rest = env assignments. Prints: label | image | delta | RAM | pool headroom
BASE=""
row() {
    label=$1; shift
    echo "== $label  ($*)" >&2
    if ! env "$@" ./build.sh >"$LOG/$label.txt" 2>&1; then
        printf '%-22s | build failed (see %s)\n' "$label" "$LOG/$label.txt"
        return 0
    fi
    line=$(grep -o 'image [0-9]* B; RAM [^;]*; lowram [^;]*; pool [^;]*' "$LOG/$label.txt" | tail -1)
    img=$(echo "$line" | sed -n 's/^image \([0-9]*\) B.*/\1/p')
    ram=$(echo "$line" | sed -n 's/.*RAM \.data+\.bss \([0-9]*\) B.*/\1/p')
    pool=$(echo "$line" | sed -n 's/.*pool \([0-9]*\) B.*/\1/p')
    if [ -z "$BASE" ]; then BASE=$img; fi
    if [ -n "$img" ] && [ -n "$BASE" ] && [ "$label" != "baseline" ]; then
        d=$((img - BASE))
        printf '%-22s | %8d | %+7d | %6s | %s\n' "$label" "$img" "$d" "${ram:--}" "${pool:--}"
    else
        printf '%-22s | %8s | %7s | %6s | %s\n' "$label" "${img:--}" "-" "${ram:--}" "${pool:--}"
    fi
}

{
    echo "# SLOOP image measurements"
    echo
    echo "Generated by \`tools/measure_flash.sh\` on $(date -u '+%Y-%m-%d %H:%M UTC')."
    echo "App slot: 581,564 B (\`tools/fm1pkg_make.py\` APP_SLOT). Baseline = the build with no flags set."
    echo
    echo "## Data blobs (exact, no cross-compiler needed)"
    echo
    echo "| blob | bytes | share of the 581,564 B slot |"
    echo "| --- | ---: | ---: |"
    [ -n "$SAMPLES" ] && echo "| \`SMP_DATA\` (8 CC0 sample sets, IMA ADPCM) | $SAMPLES | $(awk "BEGIN{printf \"%.1f\", 100*$SAMPLES/581564}")% |"
    [ -n "$ICONS" ] && echo "| \`felucca_icons.h\` (86 parameter icons, 1 bpp) | $ICONS | $(awk "BEGIN{printf \"%.1f\", 100*$ICONS/581564}")% |"
    [ -n "$LOGO" ] && echo "| boot logo RLE (not in a build with \`FELUCCA_LOGO_TEXT=1\`) | $LOGO | $(awk "BEGIN{printf \"%.1f\", 100*$LOGO/581564}")% |"
    echo
    echo "## Builds"
    echo
    echo "| variant | image B | delta vs baseline | RAM .data+.bss B | pool headroom |"
    echo "| --- | ---: | ---: | ---: | ---: |"
} >"$OUT/table.md"

row baseline >"$OUT/row.txt"; cat "$OUT/row.txt" >>"$OUT/table.md"
row logo_text FELUCCA_LOGO_TEXT=1 >>"$OUT/table.md"
if [ "$QUICK" = 0 ]; then
    row no_uac FELUCCA_UAC=0 >>"$OUT/table.md"
    row no_uart FELUCCA_UART=0 >>"$OUT/table.md"
    row no_icons FELUCCA_ICONS=0 >>"$OUT/table.md"
    row kid_candidate FELUCCA_UAC=0 FELUCCA_ICONS=0 >>"$OUT/table.md"
    row kid_candidate_uart FELUCCA_UAC=0 FELUCCA_ICONS=0 FELUCCA_UART=0 >>"$OUT/table.md"
fi
row cdc_built FELUCCA_CDC=1 >>"$OUT/table.md"

{
    echo
    echo "\`cdc_built\` is a check on the tool: SLOOP 2.7 says the USB console cost '6-8 KB' when it was cut."
    echo "If that row is in that range, the flag plumbing and this script are honest."
    echo
    echo "\`logo_text\` reads 0 if the baseline already fell back to the text logo (build.py does that by itself"
    echo "when the image overflows), which tells you that trick is spent."
    echo
    echo "No row for the arranger: it cannot be cut with a flag today (ui_song.c uses it unguarded), and at"
    echo "0.3 % of the code it is not worth the work."
    echo
    echo "## Where the code is (host proxy, for ranking only)"
    echo
    echo "Absolute bytes here are x86-64, not pi32v2: use the *shares* to decide what to cut, then the"
    echo "table above to confirm. Regenerate with \`tools/measure_code.sh\`."
} >>"$OUT/table.md"

cp "$OUT/table.md" build/measurements.md
echo
cat "$OUT/table.md"
echo
echo "written: build/measurements.md   (build logs in $LOG/)"
